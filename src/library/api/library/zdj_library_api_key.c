zdj_library_camelot_t zdj_library_get_camelot( 
	zdj_library_key_t current_key, 
	zdj_library_key_t new_key 
) {
	// printf( "zdj_library_get_camelot: %d -> %d\n", 
	// 	current_key,
	// 	new_key
	// );
	// Bounds check the inputs
	if( current_key < 0 ||
		current_key > ZDJ_LIBRARY_KEY_COUNT || 
		new_key < 0 ||
		new_key > ZDJ_LIBRARY_KEY_COUNT 
	) {
		return ZDJ_LIBRARY_CAMELOT_NONE;
	}
    
	// Swap into numeric key names for Camelot logic
	zdj_library_key_numeric_t current_num = (zdj_library_key_numeric_t)current_key;
	zdj_library_key_numeric_t new_num = (zdj_library_key_numeric_t)new_key;

	return _zdj_library_camelot_lut[ current_num ][ new_num ];
}

